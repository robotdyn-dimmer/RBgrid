#!/usr/bin/env node
/**
 * Regenerates src/i18n/locales/<lang>/index.ts from the phrase files <lang>/<ns>.json, and the
 * language repository public/static/lang/ (static/: the only folder the hub serves for a kit): one <lang>.json pack per language other than the built-in
 * one (en) plus index.json listing every language (operator 18.10: English ships in the app,
 * the others load on demand — from the hub's file system or this repository).
 * Each namespace's flat {"key": "text"} becomes "<ns>.<key>". `_meta.json` = {label, intl}.
 * `--check` exits 1 when anything generated is stale (used by the i18n test / CI).
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const BUILTIN = 'en';
const root = path.join(__dirname, '..', 'src', 'i18n', 'locales');
const repo = path.join(__dirname, '..', 'public', 'static', 'lang');
const check = process.argv.includes('--check');
let stale = false;

function write(file, text) {
  const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (cur === text) return;
  stale = true;
  if (check) { console.error(`stale: ${path.relative(process.cwd(), file)}`); return; }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  console.log(`wrote ${path.relative(process.cwd(), file)}`);
}

const index = { builtin: BUILTIN, languages: [] };
for (const lang of fs.readdirSync(root).filter((d) => fs.statSync(path.join(root, d)).isDirectory()).sort()) {
  const dir = path.join(root, lang);
  const nss = fs.readdirSync(dir).filter((f) => f.endsWith('.json') && !f.startsWith('_')).map((f) => f.slice(0, -5)).sort();
  const id = (ns) => `ns_${ns.replace(/[^A-Za-z0-9]/g, '_')}`;
  write(path.join(dir, 'index.ts'), [
    `// GENERATED by scripts/i18n-index.js — do not edit; run \`npm run i18n:index\`.`,
    ...nss.map((ns) => `import ${id(ns)} from './${ns}.json';`),
    '',
    `const prefix = (ns: string, o: Record<string, string>): Record<string, string> =>`,
    `  Object.fromEntries(Object.entries(o).map(([k, v]) => [\`\${ns}.\${k}\`, v]));`,
    '',
    `const catalog: Record<string, string> = {`,
    ...nss.map((ns) => `  ...prefix('${ns}', ${id(ns)}),`),
    `};`,
    `export default catalog;`,
    '',
  ].join('\n'));

  const meta = JSON.parse(fs.readFileSync(path.join(dir, '_meta.json'), 'utf8'));
  const phrases = {};
  for (const ns of nss) {
    const o = JSON.parse(fs.readFileSync(path.join(dir, `${ns}.json`), 'utf8'));
    for (const [k, v] of Object.entries(o)) phrases[`${ns}.${k}`] = v;
  }
  const body = JSON.stringify(phrases);
  const hash = crypto.createHash('sha1').update(body).digest('hex').slice(0, 10);
  const entry = { code: lang, label: meta.label, intl: meta.intl, hash };
  if (lang !== BUILTIN) {
    const pack = JSON.stringify({ code: lang, label: meta.label, intl: meta.intl, hash, phrases });
    write(path.join(repo, `${lang}.json`), pack);
    entry.file = `${lang}.json`;
    entry.bytes = Buffer.byteLength(pack);
  }
  index.languages.push(entry);
}
write(path.join(repo, 'index.json'), JSON.stringify(index, null, 2) + '\n');
if (check && stale) process.exit(1);
